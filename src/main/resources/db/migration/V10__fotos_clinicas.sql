CREATE TABLE fotos_clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES pacientes(id),
    data_captura DATE NOT NULL,
    regiao VARCHAR(100) NOT NULL,
    observacao VARCHAR(2000) NOT NULL DEFAULT '',
    criado_em TIMESTAMP NOT NULL,
    autor VARCHAR(255) NOT NULL,
    tipo_conteudo VARCHAR(20) NOT NULL CHECK (tipo_conteudo IN ('image/jpeg', 'image/png')),
    conteudo BYTEA NOT NULL CHECK (octet_length(conteudo) BETWEEN 1 AND 5242880)
);

CREATE INDEX idx_fotos_clinicas_paciente_data ON fotos_clinicas (paciente_id, data_captura DESC, id DESC);
