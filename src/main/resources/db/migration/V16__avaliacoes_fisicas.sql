CREATE TABLE avaliacoes_fisicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL REFERENCES pacientes(id),
    data_avaliacao DATE NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    observacao VARCHAR(2000) NOT NULL DEFAULT '',
    criado_em TIMESTAMP NOT NULL,
    autor VARCHAR(255) NOT NULL,
    nome_arquivo VARCHAR(255) NOT NULL,
    tipo_conteudo VARCHAR(20) NOT NULL CHECK (tipo_conteudo IN ('image/jpeg', 'image/png', 'application/pdf')),
    conteudo BYTEA NOT NULL CHECK (octet_length(conteudo) BETWEEN 1 AND 10485760)
);

CREATE INDEX idx_avaliacoes_fisicas_paciente_data ON avaliacoes_fisicas (paciente_id, data_avaliacao DESC, id DESC);
