-- V6: Email de usuários e reset de senha nativo (spec 05, Rota B)
-- Idempotente: pode ser executada em produção.

ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS email VARCHAR(255);

-- Nula por enquanto: popular o email do usuário admin existente manualmente
-- antes de considerar torná-la NOT NULL. Índice único aceita múltiplos NULLs.
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_email ON usuarios (email);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
    token_hash VARCHAR(255) NOT NULL,
    expira_em TIMESTAMP NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_password_reset_usuario ON password_reset_tokens (usuario_id);
