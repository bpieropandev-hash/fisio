              COALESCE((SELECT MAX(id) FROM assinaturas), 1));
SELECT setval(pg_get_serial_sequence('atendimentos', 'id'),
              COALESCE((SELECT MAX(id) FROM atendimentos), 1));
SELECT setval(pg_get_serial_sequence('cobrancas_mensais', 'id'),
              COALESCE((SELECT MAX(id) FROM cobrancas_mensais), 1));
SELECT setval(pg_get_serial_sequence('usuarios', 'id'),
