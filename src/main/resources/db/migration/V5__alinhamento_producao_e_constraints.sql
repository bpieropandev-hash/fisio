-- V5: Alinha o repositório com o schema real de produção (Railway) e adiciona
-- constraints de integridade que faltavam.
-- Idempotente: pode ser executada em produção (objetos já existentes são ignorados).
-- Em produção, executar com: SET search_path TO master;

-- ============================================================
-- 1. Alinhamento: coluna exportado_receita (feature Receita Saúde, em andamento)
-- ============================================================
ALTER TABLE atendimentos
    ADD COLUMN IF NOT EXISTS exportado_receita BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE cobrancas_mensais
    ADD COLUMN IF NOT EXISTS exportado_receita BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_atendimentos_exportado_receita
    ON atendimentos (exportado_receita, status_pagamento);

CREATE INDEX IF NOT EXISTS idx_cobrancas_exportado_receita
    ON cobrancas_mensais (exportado_receita, status);

-- ============================================================
-- 2. Alinhamento: tabela paciente_anexos (upload de documentos, em andamento)
-- ============================================================
CREATE TABLE IF NOT EXISTS paciente_anexos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    nome_original VARCHAR(255) NOT NULL,
    tipo_arquivo VARCHAR(100) NOT NULL,
    tamanho BIGINT NOT NULL,
    data_upload TIMESTAMP NOT NULL DEFAULT now(),
    storage_key VARCHAR(512) NOT NULL,
    CONSTRAINT fk_paciente_anexos_paciente FOREIGN KEY (paciente_id)
        REFERENCES pacientes(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_paciente_anexos_paciente_id
    ON paciente_anexos (paciente_id);

-- ============================================================
-- 3. Integridade: cobrança mensal única por (assinatura, mês, ano)
--    A idempotência da geração dependia só de check em código — corrida entre
--    scheduler e geração manual podia duplicar cobrança.
-- ============================================================
CREATE UNIQUE INDEX IF NOT EXISTS uq_cobranca_assinatura_mes_ano
    ON cobrancas_mensais (assinatura_id, mes_referencia, ano_referencia);

-- ============================================================
-- 4. Integridade: login de usuário único
-- ============================================================
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_login
    ON usuarios (login);

-- ============================================================
