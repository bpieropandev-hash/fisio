CREATE TABLE evolucoes_clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id INTEGER NOT NULL REFERENCES atendimentos(id),
    versao INTEGER NOT NULL CHECK (versao > 0),
    procedimentos VARCHAR(300) NOT NULL,
    equipamentos VARCHAR(150) NOT NULL,
    pressao_sistolica INTEGER,
    pressao_diastolica INTEGER,
    dor INTEGER CHECK (dor BETWEEN 0 AND 10),
    observacoes VARCHAR(5000) NOT NULL,
    resumo TEXT NOT NULL,
    texto_legado TEXT NOT NULL,
    autor VARCHAR(255) NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_evolucoes_atendimento_versao UNIQUE (atendimento_id, versao),
    CONSTRAINT ck_evolucoes_pressao CHECK (
        (pressao_sistolica IS NULL AND pressao_diastolica IS NULL)
        OR (pressao_sistolica IS NOT NULL AND pressao_diastolica IS NOT NULL
            AND pressao_sistolica BETWEEN 40 AND 300
            AND pressao_diastolica BETWEEN 20 AND 200
            AND pressao_sistolica > pressao_diastolica)
    )
);
